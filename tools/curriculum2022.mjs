/** 원본 단원 문자열 -> 2022 개정 매핑 결과 배열 */
export function mapBioCurriculum(raw) {
  const v = (raw || '').replace(/\s+/g, ' ').trim();
  if (!v) return [];
  const seen = new Set();
  const out = [];
  for (const [re, subject, area, element] of BIO_MAP_RULES) {
    if (!re.test(v)) continue;
    const key = subject + '|' + area;
    if (seen.has(key)) continue;
    seen.add(key);
    const meta = SUBJECT_INDEX[subject] || { area: '과학', track: '기타' };
    out.push({ subject, track: meta.track, area, element });
  }
  return out;
}

