function pickArea(subject) {
  const v = (subject || '').trim();
  for (const [re, area] of AREA_BY_SUBJECT) if (re.test(v)) return area;
  return '기타';
}

/**
 * 타교과 연계 -> {교과, 추천 과목[]}
 * 1단계: subject 로 교과를 판정
 * 2단계: 그 교과 안에서 connection 내용으로 구체 과목을 고른다
 */
export function mapCrossSubject(subject, connection) {
  const area = pickArea(subject);
  if (area === '기타') return { area, subjects: [] };
  const hay = (subject || '') + ' ' + (connection || '');
  for (const [re, ruleArea, subjects] of CROSS_RULES) {
    if (ruleArea !== area) continue;
    if (re.test(hay)) return { area, subjects };
  }
  return { area, subjects: DEFAULT_COURSES[area] || [] };
}
